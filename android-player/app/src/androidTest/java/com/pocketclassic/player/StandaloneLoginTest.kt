package com.pocketclassic.player

import android.graphics.Bitmap
import android.os.Bundle
import android.os.SystemClock
import android.security.NetworkSecurityPolicy
import androidx.lifecycle.ViewModelProvider
import androidx.test.core.app.ActivityScenario
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import androidx.test.runner.lifecycle.ActivityLifecycleMonitorRegistry
import androidx.test.runner.lifecycle.Stage
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File

/** Runs the actual Android login UI and HTTPS client; never imports desktop cookies. */
@RunWith(AndroidJUnit4::class)
@androidx.annotation.OptIn(androidx.media3.common.util.UnstableApi::class)
class StandaloneLoginTest {
    @Test fun authorizeOnDeviceAndReadAccountDirectly() {
        val instrumentation=InstrumentationRegistry.getInstrumentation();val context=instrumentation.targetContext
        org.junit.Assume.assumeTrue("Requires a fresh user authorization",InstrumentationRegistry.getArguments().getString("authorize")=="true")
        assertFalse(NetworkSecurityPolicy.getInstance().isCleartextTrafficPermitted("10.0.2.2"))
        val scenario=ActivityScenario.launch(MainActivity::class.java)
        lateinit var vm: PlayerViewModel
        instrumentation.runOnMainSync {
            val activity=ActivityLifecycleMonitorRegistry.getInstance().getActivitiesInStage(Stage.RESUMED).filterIsInstance<MainActivity>().first()
            vm=ViewModelProvider(activity)[PlayerViewModel::class.java];vm.beginLogin()
        }
        val deadline=SystemClock.elapsedRealtime()+200_000;var saved=false;var connected=false
        while(SystemClock.elapsedRealtime()<deadline) {
            instrumentation.runOnMainSync {
                if(!saved && vm.state.qrImage!=null) {
                    File(context.filesDir,"standalone-login.png").outputStream().use { vm.state.qrImage!!.compress(Bitmap.CompressFormat.PNG,100,it) }
                    saved=true;instrumentation.sendStatus(2,Bundle().apply { putString("stream","\nNATIVE_LOGIN_QR_READY\n") })
                }
                connected=vm.state.connected
            }
            if(connected)break
            Thread.sleep(400)
        }
        assertTrue("Please confirm the fresh authorization QR generated by the Android app",connected)
        val store=MusicSessionStore(context);val session=store.read()!!
        assertTrue(session.cookie.contains("MUSIC_U="));assertTrue(session.userId>0)
        assertEquals(session,MusicSessionStore(context).read())
        val api=NetEaseApi(store)
        assertTrue(api.status().getBoolean("authenticated"))
        assertTrue(api.browserApi("playlists").getJSONArray("playlists").length()>0)
        val daily=api.browserApi("daily").getJSONArray("tracks");assertTrue(daily.length()>0)
        assertTrue(api.resolve(daily.getJSONObject(0).getLong("id")).url.startsWith("http"))
        assertTrue(api.roaming().isNotEmpty())
        instrumentation.sendStatus(2,Bundle().apply { putString("stream","\nSTANDALONE_ACCOUNT_PLAYLIST_DAILY_RADIO_AUDIO_PASSED\n") })
        instrumentation.runOnMainSync { ActivityLifecycleMonitorRegistry.getInstance().getActivitiesInStage(Stage.RESUMED).filterIsInstance<MainActivity>().forEach { it.finish() } }
    }
}
